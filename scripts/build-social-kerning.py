#!/usr/bin/env python3
"""Extracts GPOS pair kerning for printable ASCII (incl. space) from Inter ExtraBold into a PHP array.

GD (FreeType) only reads the legacy `kern` table, and Inter ships kerning in GPOS, so the social
card generator applies these pairs itself when drawing the headline. Values are font units
(2048 per em). Requires fontTools: pip install fonttools
"""
import sys
from pathlib import Path
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
font_path = root / "dreamhost-site/assets/social/Inter-ExtraBold.ttf"
out_path = root / "dreamhost-site/app/social-kerning.php"

font = TTFont(str(font_path))
cmap = font.getBestCmap()
gpos = font["GPOS"].table
chars = [chr(c) for c in range(0x20, 0x7F)] + ["…", "’", "‘", "“", "”", "–", "—"]
glyph = {c: cmap[ord(c)] for c in chars if ord(c) in cmap}

lookups = set()
for fr in gpos.FeatureList.FeatureRecord:
    if fr.FeatureTag == "kern":
        lookups.update(fr.Feature.LookupListIndex)


def subtables(lookup):
    for st in lookup.SubTable:
        yield st.ExtSubTable if lookup.LookupType == 9 else st


def lookup_value(lookup, g1, g2):
    """XAdvance from the first subtable of this lookup that matches the pair."""
    for st in subtables(lookup):
        if not hasattr(st, "Coverage") or g1 not in st.Coverage.glyphs:
            continue
        if st.Format == 1:
            ps = st.PairSet[st.Coverage.glyphs.index(g1)]
            for rec in ps.PairValueRecord:
                if rec.SecondGlyph == g2:
                    return getattr(rec.Value1, "XAdvance", 0) if rec.Value1 else 0
        elif st.Format == 2:
            c1 = st.ClassDef1.classDefs.get(g1, 0)
            c2 = st.ClassDef2.classDefs.get(g2, 0)
            rec = st.Class1Record[c1].Class2Record[c2]
            return getattr(rec.Value1, "XAdvance", 0) if rec.Value1 else 0
    return 0


def kern(g1, g2):
    # Every lookup in the kern feature applies, so the adjustments add up.
    return sum(lookup_value(gpos.LookupList.Lookup[idx], g1, g2) for idx in sorted(lookups))


pairs = {}
for a, ga in glyph.items():
    for b, gb in glyph.items():
        v = kern(ga, gb)
        if v:
            pairs[a + b] = v

lines = ["<?php", "declare(strict_types=1);", "", "// Loaded by app/social-card.php; refuse a direct request.", "defined('ROOT_PATH') || exit;", "", "// Generated by scripts/build-social-kerning.py from Inter-ExtraBold.ttf (GPOS kern). Font units, 2048/em.",
         "return ["]
for k in sorted(pairs):
    lines.append("    %s => %d," % ("'" + k.replace("\\", "\\\\").replace("'", "\\'") + "'", pairs[k]))
lines.append("];")
out_path.write_text("\n".join(lines) + "\n")
print("wrote", out_path, len(pairs), "pairs")
